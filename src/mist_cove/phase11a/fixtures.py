DEFAULT_STATE={'synthetic_weight':[.125,.25,.5],'synthetic_buffer':[1.,2.]}


def default_identity():
    value={'experiment':'SYNTHETIC_P3B','variant':'raw_context','seed':123,'implementation_commit':'a'*40}
    for name in ('split_fingerprint','normalization_fingerprint','bank_sha256','config_sha256','environment_sha256'):
        value[name]=sha256(('generated '+name).encode())
    value['run_fingerprint']=sha256(canonical(value));return value


@dataclass(frozen=True)
class IndependentFixtureReference:
    capability:object
    case_number:int
    creation_sha256:str
    completion_sha256:str
    identity_bytes:bytes
    checkpoint_sha256:str
    model_state_digest:str
    reference_kind:str='CHECKPOINT_BYTES_SHA256'


class FixtureCase:
    def __init__(self,capability,lab,number,fd):
        if capability is not _CAP:raise PermissionError('generated fixture capability required')
        self._capability=capability;self._lab=lab;self._number=number;self._fd=fd
        self._owned={};self.reference=None;self._closed=False

    def valid(self):
        if self._closed or self._lab._closed or self._lab._cases.get(self._number) is not self:
            raise PermissionError('expired or unowned fixture capability')

    def _check_owned(self,name,info):
        if not stat.S_ISREG(info.st_mode) or info.st_nlink!=1 or (info.st_dev,info.st_ino)!=self._owned.get(name):
            raise InvalidEvidence('unowned/symlink/nonregular generated file')

    def _create(self,name,data):
        if name not in FILES or type(data) is not bytes:raise PermissionError('fixed generated fixture name/bytes only')
        fd=os.open(name,os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW,0o600,dir_fd=self._fd)
        try:
            with os.fdopen(fd,'wb',closefd=False) as stream:stream.write(data);stream.flush();os.fsync(fd)
            st=os.fstat(fd);self._owned[name]=(st.st_dev,st.st_ino)
        finally:os.close(fd)

    def open_owned(self,name):
        self.valid()
        if name not in FILES:raise PermissionError('not an issued fixture file')
        before=os.stat(name,dir_fd=self._fd,follow_symlinks=False);self._check_owned(name,before)
        fd=os.open(name,os.O_RDONLY|os.O_NOFOLLOW|os.O_NONBLOCK,dir_fd=self._fd)
        try:self._check_owned(name,os.fstat(fd))
        except BaseException:os.close(fd);raise
        return fd

    def overwrite(self,name,data):
        """Adversarial mutation of this lab's own originally generated inode."""
        self.valid()
        if name not in FILES or type(data) is not bytes:raise PermissionError('generated bytes only')
        before=os.stat(name,dir_fd=self._fd,follow_symlinks=False);self._check_owned(name,before)
        fd=os.open(name,os.O_WRONLY|os.O_NOFOLLOW|os.O_NONBLOCK,dir_fd=self._fd)
        try:
            self._check_owned(name,os.fstat(fd));os.ftruncate(fd,0);os.write(fd,data);os.fsync(fd)
        finally:os.close(fd)

    def bytes(self,name):
        fd=self.open_owned(name)
        try:return os.pread(fd,1048577,0)
        finally:os.close(fd)

    def remove(self,name):
        self.valid()
        if name not in FILES:raise PermissionError('generated name only')
        os.unlink(name,dir_fd=self._fd)

    def outside_symlink(self):
        self.remove('candidate.bin')
        os.symlink('../outside_generated.bin','candidate.bin',dir_fd=self._fd)

    def close(self):
        if not self._closed:os.close(self._fd);self._closed=True


class FixtureLab:
    """Always creates a new private temporary directory, never adopts a root."""
    def __init__(self):
        self._temporary=tempfile.TemporaryDirectory(prefix='mist-xia-generated-')
        self._fd=os.open(self._temporary.name,os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW)
        self._cases={};self._closed=False
        fd=os.open('outside_generated.bin',os.O_WRONLY|os.O_CREAT|os.O_EXCL,0o600,dir_fd=self._fd)
        os.write(fd,b'owned synthetic outside-case sentinel');os.close(fd)

    def new_case(self,*,identity_changes=None,state=None,unsafe=False,malformed=None):
        if self._closed:raise PermissionError('expired lab')
        number=len(self._cases)+1;name=f'generated{number:04}'
        os.mkdir(name,0o700,dir_fd=self._fd)
        fd=os.open(name,os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW,dir_fd=self._fd)
        case=FixtureCase(_CAP,self,number,fd);self._cases[number]=case
        identity=default_identity();identity.update(identity_changes or {});validate_identity(identity,synthetic=True)
        state=DEFAULT_STATE if state is None else state;state_digest=sha256(canonical(state))
        envelope={'schema':'xia-generated-envelope-v1','identity':identity,'state':state,'model_state_digest':state_digest,'metrics':{'score':.5}}
        payload=MAGIC+canonical(envelope)
        if unsafe:
            # Generated executable pickle tripwire. It is never parsed/executed.
            sentinel=self._temporary.name+'/UNSAFE_EXECUTED'
            payload=b"cos\nsystem\n(S'touch "+sentinel.encode()+b"'\ntR."
        format_='UNSAFE_PICKLE_FIXTURE' if unsafe else 'GENERATED_JSON'
        creation={'schema':'xia-fixture-creation-v1','identity':identity,'checkpoint_sha256':sha256(payload),
                  'checkpoint_size':len(payload),'model_state_digest':state_digest,'format':format_}
        raw_creation=canonical(creation)
        if malformed=='duplicate':raw_creation=b'{"schema":"duplicate",'+raw_creation[1:]
        complete={'schema':'xia-fixture-completion-v1','identity':identity,'creation_sha256':sha256(raw_creation),
                  'checkpoint_sha256':sha256(payload),'checkpoint_size':len(payload),'model_state_digest':state_digest,'format':format_}
        if malformed=='contradiction':complete['checkpoint_sha256']='0'*64
        raw_complete=canonical(complete)
        for file,data in [('candidate.bin',payload),('creation.json',raw_creation),('completion.json',raw_complete),('local_sidecar.json',raw_creation)]:case._create(file,data)
        case.reference=IndependentFixtureReference(_CAP,number,sha256(raw_creation),sha256(raw_complete),canonical(identity),sha256(payload),state_digest)
        return case

    def unsafe_executed(self):
        try:os.stat('UNSAFE_EXECUTED',dir_fd=self._fd,follow_symlinks=False);return True
        except FileNotFoundError:return False

    def close(self):
        if not self._closed:
            for case in self._cases.values():case.close()
            os.close(self._fd);self._temporary.cleanup();self._closed=True

    def __enter__(self):return self
    def __exit__(self,*args):self.close()
